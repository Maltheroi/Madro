#!/usr/bin/env python3
"""Extracts Frida 5.5 nutrient values for the foods in supabase/seed-data/frida-map.mjs.

Usage: python3 scripts/frida-extract.py Frida_5.5_Dataset.xlsx
Writes supabase/seed-data/frida-values.mjs. Needs openpyxl.

Frida 5.5 (doi:10.11583/DTU.29500682) is CC BY 4.0. Values are per 100 g
edible part. Energy and carbohydrate use the labelling (EU 1169/2011)
parameters, falling back to the general ones; salt falls back to sodium x 2.5.
A value Frida does not give stays null.
"""
import json
import re
import sys
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parent.parent
PARAMS = {
    "359": "kcal_lab", "356": "kcal", "218": "protein", "318": "carb_lab", "172": "carb",
    "141": "fat", "168": "fiber", "245": "sugars", "248": "satfat", "327": "salt", "201": "sodium",
}


def main(xlsx: str) -> None:
    mapping = re.findall(r'\["([a-z0-9-]+)",\s*(\d+),\s*"([a-z_]+)"\]',
                         (ROOT / "supabase/seed-data/frida-map.mjs").read_text())
    wanted = {food_id for _, food_id, _ in mapping}
    ws = openpyxl.load_workbook(xlsx, read_only=True, data_only=True)["Data_Table"]
    header, foods = None, {}
    for i, row in enumerate(ws.iter_rows(values_only=True)):
        if i == 3:
            header = [str(v) for v in row]
        if i < 4 or row[2] is None or str(row[2]) not in wanted:
            continue
        rec = {"name": row[0]}
        for j, pid in enumerate(header):
            if pid in PARAMS:
                v = row[j]
                rec[PARAMS[pid]] = None if v in (None, "", "NULL") else float(v)
        foods[str(row[2])] = rec

    def r2(v):
        return None if v is None else round(v, 2)

    out = []
    for slug, food_id, state in mapping:
        f = foods.get(food_id)
        if f is None:
            sys.exit(f"Frida food {food_id} for {slug} not found")
        kcal = f["kcal_lab"] if f["kcal_lab"] is not None else f["kcal"]
        carb = f["carb_lab"] if f["carb_lab"] is not None else f["carb"]
        salt = f["salt"] if f["salt"] is not None else (
            f["sodium"] * 2.5 / 1000 if f["sodium"] is not None else None)
        out.append([slug, int(food_id), f["name"], state, r2(kcal), r2(f["protein"]), r2(carb),
                    r2(f["fat"]), r2(f["fiber"]), r2(f["sugars"]), r2(f["satfat"]), r2(salt)])

    body = ",\n".join("  " + json.dumps(row, ensure_ascii=False) for row in out)
    (ROOT / "supabase/seed-data/frida-values.mjs").write_text(
        "// GENERATED by scripts/frida-extract.py from Frida 5.5. Do not edit by hand.\n"
        "// Source: Marija Langwagen, Jette Jacobsen, Tue Christensen and Anders Poulsen: The Danish\n"
        "// Food Composition Database, Frida version 5.5, November 2025, National Food Institute,\n"
        "// Technical University of Denmark. https://doi.org/10.11583/DTU.29500682 (CC BY 4.0)\n"
        "//\n"
        "// [slug, FoodID, Frida name, state, kcal, protein, carbohydrate, fat, fiber, sugars,\n"
        "//  saturated fat, salt] per 100 g; null = not given by Frida.\n"
        "// prettier-ignore\n"
        f"export const fridaValues = [\n{body},\n];\n")
    print(f"{len(out)} foods written")


if __name__ == "__main__":
    main(sys.argv[1])
