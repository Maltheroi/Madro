#!/usr/bin/env node
// SQL that marks Frida 5.5 as a verified CC BY 4.0 source and writes its
// values to public.nutrition_facts for the mapped catalogue ingredients.
// Used by scripts/generate-seed.mjs and, run directly, prints the SQL for a
// migration on an existing database: node scripts/frida-sql.mjs
import { fileURLToPath } from "node:url";
import { fridaValues } from "../supabase/seed-data/frida-values.mjs";

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const num = (v) => (v === null || v === undefined ? "null" : String(v));

export const FRIDA_ATTRIBUTION =
  "Marija Langwagen, Jette Jacobsen, Tue Christensen and Anders Poulsen: The Danish Food Composition Database, Frida version 5.5, November 2025, National Food Institute, Technical University of Denmark. https://doi.org/10.11583/DTU.29500682";

export function fridaSql() {
  const rows = fridaValues
    .map(
      ([slug, id, , state, kcal, p, c, f, fib, sug, sat, salt]) =>
        `  (${q(slug)}, ${q(state)}, ${q(id)}, ${num(kcal)}, ${num(p)}, ${num(c)}, ${num(f)}, ${num(fib)}, ${num(sug)}, ${num(sat)}, ${num(salt)})`,
    )
    .join(",\n");
  return `-- Frida 5.5 (DTU Fødevareinstituttet), CC BY 4.0. Values per 100 g from
-- supabase/seed-data/frida-values.mjs (generated by scripts/frida-extract.py).
insert into public.nutrition_sources (key, name, url, license, attribution, version, retrieved_at, verification_status, notes)
values ('frida', 'Frida – DTU Fødevareinstituttet', 'https://doi.org/10.11583/DTU.29500682', 'CC BY 4.0',
        ${q(FRIDA_ATTRIBUTION)}, '5.5', '2026-10-13', 'verified',
        'Official Danish food composition database. Dataset files are CC BY 4.0 (Figshare record 29500682).')
on conflict (key) do update set
  name = excluded.name, url = excluded.url, license = excluded.license, attribution = excluded.attribution,
  version = excluded.version, retrieved_at = excluded.retrieved_at,
  verification_status = excluded.verification_status, notes = excluded.notes;

insert into public.nutrition_facts (ingredient_id, food_state, source_id, source_version, source_food_code,
  energy_kcal, protein_g, carbohydrate_g, fat_g, fiber_g, sugars_g, saturated_fat_g, salt_g, confidence, last_verified_at)
select i.id, v.state::public.food_state, s.id, '5.5', v.code,
       v.kcal, v.protein, v.carb, v.fat, v.fiber, v.sugars, v.satfat, v.salt, 'high', '2026-10-13'
from (values
${rows}
) as v(slug, state, code, kcal, protein, carb, fat, fiber, sugars, satfat, salt)
join public.ingredients i on i.slug = v.slug
cross join (select id from public.nutrition_sources where key = 'frida') s
on conflict (ingredient_id, food_state, source_id) do update set
  source_version = excluded.source_version, source_food_code = excluded.source_food_code,
  energy_kcal = excluded.energy_kcal, protein_g = excluded.protein_g, carbohydrate_g = excluded.carbohydrate_g,
  fat_g = excluded.fat_g, fiber_g = excluded.fiber_g, sugars_g = excluded.sugars_g,
  saturated_fat_g = excluded.saturated_fat_g, salt_g = excluded.salt_g,
  confidence = excluded.confidence, last_verified_at = excluded.last_verified_at;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.stdout.write(fridaSql());
