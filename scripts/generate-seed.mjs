#!/usr/bin/env node
// Generates supabase/seed.sql from supabase/seed-data/catalog.mjs.
// Usage: node scripts/generate-seed.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { ingredients, recipes, demoRetailers } from "../supabase/seed-data/catalog.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const arr = (a) => `array[${a.map(q).join(", ")}]::text[]`;
const num = (v) => (v === null || v === undefined ? "null" : String(v));

// Deterministic pseudo-random in [0, 1) from a string.
function rand(s) {
  let h = 2166136261;
  for (const c of s) h = Math.imul(h ^ c.charCodeAt(0), 16777619);
  return ((h >>> 0) % 10000) / 10000;
}

const toKgOrL = { g: 0.001, kg: 1, ml: 0.001, l: 1, dl: 0.1 };

const out = [];
out.push(`-- GENERATED by scripts/generate-seed.mjs from supabase/seed-data/catalog.mjs. Do not edit by hand.
-- Development data only:
--   * nutrition values are approximate and unverified (source 'dev-seed-approximate', confidence low)
--   * prices are SYNTHETIC fixtures for fictional demo chains (is_synthetic = true)
`);
out.push(`insert into public.nutrition_sources (key, name, license, version, verification_status, notes) values
  ('dev-seed-approximate', 'Udviklingsdata (omtrentlige værdier)', 'Internal development data', '2026-10-12', 'development',
   'Approximate values entered by hand for development. Not verified against Frida. Must be replaced before launch.')
on conflict (key) do nothing;
`);

for (const [slug, name, category, allergens, diet, opts, state, kcal, p, c, f, fib, sug, sat, salt] of ingredients) {
  out.push(`insert into public.ingredients (slug, canonical_name, name_da, category, default_unit, density_g_per_ml, grams_per_piece, cooked_yield_factor, allergens, diet_tags, shelf_stable)
values (${q(slug)}, ${q(slug.replaceAll("-", " "))}, ${q(name)}, ${q(category)}, ${q(opts.unit ?? "g")}, ${num(opts.density)}, ${num(opts.gpp)}, ${num(opts.yield)}, ${arr(allergens)}, ${arr(diet)}, ${opts.shelfStable ? "true" : "false"})
on conflict (slug) do nothing;
insert into public.nutrition_facts (ingredient_id, food_state, source_id, source_version, energy_kcal, protein_g, carbohydrate_g, fat_g, fiber_g, sugars_g, saturated_fat_g, salt_g, confidence)
select i.id, ${q(state)}, s.id, '2026-10-12', ${kcal}, ${p}, ${c}, ${f}, ${num(fib)}, ${num(sug)}, ${num(sat)}, ${num(salt)}, 'low'
from public.ingredients i, public.nutrition_sources s where i.slug = ${q(slug)} and s.key = 'dev-seed-approximate'
on conflict (ingredient_id, food_state, source_id) do nothing;`);
}

for (const [slug, name, desc, servings, prep, cook, mealTypes, difficulty, steps, lines] of recipes) {
  out.push(`insert into public.recipes (slug, name_da, description_da, servings, prep_minutes, cook_minutes, meal_types, instructions_da, difficulty)
values (${q(slug)}, ${q(name)}, ${q(desc)}, ${servings}, ${prep}, ${cook}, array[${mealTypes.map(q).join(", ")}]::public.meal_slot[], ${arr(steps)}, ${q(difficulty)})
on conflict (slug) do nothing;`);
  lines.forEach(([ing, qty, unit, st, optional], idx) => {
    out.push(`insert into public.recipe_ingredients (recipe_id, ingredient_id, position, quantity, unit, food_state, optional)
select r.id, i.id, ${idx}, ${qty}, ${q(unit)}, ${q(st)}, ${optional ? "true" : "false"} from public.recipes r, public.ingredients i
where r.slug = ${q(slug)} and i.slug = ${q(ing)} and not exists (select 1 from public.recipe_ingredients x where x.recipe_id = r.id and x.position = ${idx});`);
  });
}

// Synthetic retail fixtures.
out.push(`insert into public.data_sync_jobs (id, provider_key, job_type, status, started_at, finished_at, metadata)
values ('00000000-0000-4000-8000-000000000001', 'synthetic-fixtures', 'seed', 'succeeded', now(), now(), '{"note":"Synthetic development fixtures"}')
on conflict (id) do nothing;`);
const cities = [["8000", "Aarhus C"], ["2200", "København N"], ["5000", "Odense C"]];
for (const r of demoRetailers) {
  out.push(`insert into public.retailers (slug, name) values (${q(r.slug)}, ${q(r.name)}) on conflict (slug) do nothing;`);
  cities.forEach(([zip, city], ci) => {
    out.push(`insert into public.stores (retailer_id, name, source_key, external_id, postal_code, city)
select id, ${q(`${r.name.replace(" (syntetisk)", "")} ${city}`)}, 'synthetic-fixtures', ${q(`${r.slug}-${ci}`)}, ${q(zip)}, ${q(city)} from public.retailers where slug = ${q(r.slug)}
on conflict (source_key, external_id) do nothing;`);
  });
  for (const [slug, name, , allergens, , opts, , , , , , , , , , basePrice, packs] of ingredients) {
    if (r.skip.includes(slug)) continue;
    packs.forEach(([pq, pu], pi) => {
      const ext = `${r.slug}-${slug}-${pi}`;
      let price;
      if (pu === "stk") {
        // stk-packed goods: base price is per kg; use piece weight
        const grams = (opts.gpp ?? 100) * pq;
        price = (basePrice * grams) / 1000;
      } else {
        price = basePrice * pq * toKgOrL[pu];
      }
      // Smaller packs cost more per unit; retailer factor; ±6 % deterministic noise.
      price *= r.factor * (1 + 0.12 * pi) * (0.94 + 0.12 * rand(ext));
      const priceOre = Math.max(100, Math.round(price / 25) * 25 - 5);
      out.push(`insert into public.products (retailer_id, source_key, external_id, name, package_quantity, package_unit, allergens)
select id, 'synthetic-fixtures', ${q(ext)}, ${q(`${name} ${String(pq).replace(".", ",")} ${pu}`)}, ${pq}, ${q(pu)}, ${arr(allergens)} from public.retailers where slug = ${q(r.slug)}
on conflict (retailer_id, source_key, external_id) do nothing;
insert into public.ingredient_product_matches (ingredient_id, product_id, quality, matched_by, confidence)
select i.id, p.id, 'exact', 'manual', 'high' from public.ingredients i, public.products p
where i.slug = ${q(slug)} and p.external_id = ${q(ext)} and p.source_key = 'synthetic-fixtures'
on conflict (ingredient_id, product_id) do nothing;
insert into public.price_observations (product_id, retailer_id, price_ore, price_type, is_synthetic, observed_at, source_key, confidence, sync_job_id)
select p.id, p.retailer_id, ${priceOre}, 'shelf', true, now(), 'synthetic-fixtures', 'low', '00000000-0000-4000-8000-000000000001'
from public.products p where p.external_id = ${q(ext)} and p.source_key = 'synthetic-fixtures'
and not exists (select 1 from public.price_observations o where o.product_id = p.id);`);
      // A few synthetic promotions to exercise offer handling.
      if (rand(ext + "promo") < 0.12) {
        out.push(`insert into public.price_observations (product_id, retailer_id, price_ore, price_type, is_synthetic, observed_at, valid_from, valid_to, source_key, confidence, sync_job_id)
select p.id, p.retailer_id, ${Math.max(100, Math.round((priceOre * 0.8) / 25) * 25 - 5)}, 'promotional', true, now(), date_trunc('week', now()), date_trunc('week', now()) + interval '7 days' - interval '1 second', 'synthetic-fixtures-promo', 'low', '00000000-0000-4000-8000-000000000001'
from public.products p where p.external_id = ${q(ext)} and p.source_key = 'synthetic-fixtures'
and (select count(*) from public.price_observations o where o.product_id = p.id) < 2;`);
      }
    });
  }
}

writeFileSync(join(root, "supabase/seed.sql"), out.join("\n\n") + "\n");
console.log(`Wrote supabase/seed.sql (${ingredients.length} ingredients, ${recipes.length} recipes, ${demoRetailers.length} demo chains)`);
