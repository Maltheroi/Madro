#!/usr/bin/env bash
# Docker-free local backend: PostgreSQL + Supabase Auth (GoTrue) + a tiny gateway.
# Prefer `npx supabase start` when Docker is available; this exists for
# environments without Docker (and for CI). Requires:
#   - PostgreSQL server binaries (initdb, pg_ctl, psql)
#   - a Supabase Auth binary: set GOTRUE_BIN (build: see docs/LOCAL_DEVELOPMENT.md)
# Writes .env.local for the app. Data lives in .local-stack/ (git-ignored).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
STATE="${LOCAL_STACK_DIR:-$ROOT/.local-stack}"
PG_PORT="${PG_PORT:-54322}"
AUTH_PORT="${AUTH_PORT:-9999}"
GATEWAY_PORT="${GATEWAY_PORT:-54321}"
GOTRUE_BIN="${GOTRUE_BIN:?Set GOTRUE_BIN to the Supabase Auth binary}"
JWT_SECRET="${LOCAL_JWT_SECRET:-local-dev-jwt-secret-at-least-32-characters}"
PG_BIN="${PG_BIN:-$(dirname "$(command -v initdb 2>/dev/null || ls /usr/lib/postgresql/*/bin/initdb | tail -1)")}"
mkdir -p "$STATE"

RUN_AS=()
if [[ "$(id -u)" == "0" ]]; then RUN_AS=(sudo -u postgres); chown postgres "$STATE"; fi
DB="postgres://postgres@127.0.0.1:$PG_PORT/postgres"
FRESH=0

if [[ ! -d "$STATE/pg" ]]; then
  mkdir -p "$STATE/pg"; [[ ${#RUN_AS[@]} -gt 0 ]] && chown postgres "$STATE/pg"
  "${RUN_AS[@]}" "$PG_BIN/initdb" -D "$STATE/pg" -U postgres --auth=trust >/dev/null
  FRESH=1
fi
if ! pg_isready -h 127.0.0.1 -p "$PG_PORT" >/dev/null 2>&1; then
  "${RUN_AS[@]}" "$PG_BIN/pg_ctl" -D "$STATE/pg" -o "-p $PG_PORT -k /tmp -c listen_addresses=127.0.0.1" -l "$STATE/pg.log" start >/dev/null
  for _ in $(seq 1 50); do pg_isready -h 127.0.0.1 -p "$PG_PORT" >/dev/null 2>&1 && break; sleep 0.2; done
fi

if [[ "$FRESH" == "1" ]]; then
  psql "$DB" -v ON_ERROR_STOP=1 -q <<SQL
create role anon nologin noinherit;
create role authenticated nologin noinherit;
create role service_role nologin noinherit bypassrls;
create user supabase_auth_admin noinherit createrole login password 'root';
create schema if not exists auth authorization supabase_auth_admin;
grant create on database postgres to supabase_auth_admin;
alter user supabase_auth_admin set search_path = 'auth';
grant usage on schema public to anon, authenticated, service_role;
alter default privileges in schema public grant all on tables to anon, authenticated, service_role;
alter default privileges in schema public grant all on sequences to anon, authenticated, service_role;
alter default privileges in schema public grant execute on functions to anon, authenticated, service_role;
SQL
fi

export GOTRUE_DB_DRIVER=postgres DB_NAMESPACE=auth
export DATABASE_URL="postgres://supabase_auth_admin:root@127.0.0.1:$PG_PORT/postgres"
export GOTRUE_JWT_SECRET="$JWT_SECRET" GOTRUE_JWT_EXP=3600 GOTRUE_JWT_AUD=authenticated
export GOTRUE_JWT_ADMIN_ROLES="service_role" GOTRUE_JWT_DEFAULT_GROUP_NAME=authenticated
export GOTRUE_API_HOST=127.0.0.1 PORT="$AUTH_PORT" API_EXTERNAL_URL="http://127.0.0.1:$GATEWAY_PORT/auth/v1"
export GOTRUE_SITE_URL="http://localhost:3000"
export GOTRUE_URI_ALLOW_LIST="http://localhost:3000/**,http://127.0.0.1:3000/**,http://localhost:3100/**"
export GOTRUE_MAILER_AUTOCONFIRM="${GOTRUE_MAILER_AUTOCONFIRM:-true}" GOTRUE_DISABLE_SIGNUP=false
export GOTRUE_PASSWORD_MIN_LENGTH=10 GOTRUE_LOG_LEVEL=warn GOTRUE_SMTP_ADMIN_EMAIL=dev@madro.local
export GOTRUE_EXTERNAL_EMAIL_ENABLED=true GOTRUE_RATE_LIMIT_EMAIL_SENT=1000

if [[ "$FRESH" == "1" ]]; then
  "$GOTRUE_BIN" migrate >/dev/null
  psql "$DB" -v ON_ERROR_STOP=1 -q -c "grant usage on schema auth to anon, authenticated, service_role; grant execute on all functions in schema auth to anon, authenticated, service_role;"
  for f in "$ROOT"/supabase/migrations/*.sql; do psql "$DB" -v ON_ERROR_STOP=1 -q -f "$f"; done
  psql "$DB" -v ON_ERROR_STOP=1 -q -f "$ROOT/supabase/seed.sql"
fi

if ! curl -s "http://127.0.0.1:$AUTH_PORT/health" >/dev/null; then
  nohup "$GOTRUE_BIN" serve >"$STATE/auth.log" 2>&1 &
  echo $! >"$STATE/auth.pid"
fi
if ! curl -s "http://127.0.0.1:$GATEWAY_PORT/auth/v1/health" >/dev/null; then
  GATEWAY_PORT="$GATEWAY_PORT" AUTH_PORT="$AUTH_PORT" nohup node "$ROOT/scripts/local-stack/gateway.mjs" >"$STATE/gateway.log" 2>&1 &
  echo $! >"$STATE/gateway.pid"
fi
for _ in $(seq 1 50); do curl -s "http://127.0.0.1:$GATEWAY_PORT/auth/v1/health" >/dev/null && break; sleep 0.2; done

ANON=$(node "$ROOT/scripts/local-stack/jwt.mjs" anon "$JWT_SECRET")
SERVICE=$(node "$ROOT/scripts/local-stack/jwt.mjs" service_role "$JWT_SECRET")
cat >"$ROOT/.env.local" <<ENV
# Generated by scripts/local-stack/start.sh — local development only.
NEXT_PUBLIC_SUPABASE_URL=http://127.0.0.1:$GATEWAY_PORT
NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=$ANON
NEXT_PUBLIC_SITE_URL=http://localhost:3000
DATABASE_URL=$DB
DATABASE_SSL=disable
SUPABASE_SERVICE_ROLE_KEY=$SERVICE
ENV
echo "Local stack ready: Postgres :$PG_PORT, Auth via http://127.0.0.1:$GATEWAY_PORT/auth/v1. Wrote .env.local"
